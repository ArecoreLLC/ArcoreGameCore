"""Engine-neutral 2D placement envelopes for 3D courses; no engine imports.

Rectangles are [min_x, min_y, max_x, max_y], in centimeters. Travel is
maximum displacement from the anchor, not a full period distance.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path


def number(value):
    return type(value) in (int, float) and abs(value) <= 10_000_000 and math.isfinite(value)


def validate(data):
    if not isinstance(data, dict) or data.get('schema_version') != 1 or data.get('units') != 'centimeters':
        raise ValueError('Expected schema_version 1 and centimeters')
    def vector(value, size):
        return isinstance(value, list) and len(value) == size and all(number(v) for v in value)
    def rect(value):
        return vector(value, 4) and value[0] < value[2] and value[1] < value[3]
    if not rect(data.get('bounds')):
        raise ValueError('bounds must be a finite, nonempty rectangle')
    if not number(data.get('grid')) or data['grid'] < 0.001:
        raise ValueError('grid must be finite and in 0.001..10000000 cm')
    if type(data.get('max_pieces')) is not int or not 1 <= data['max_pieces'] <= 1024:
        raise ValueError('max_pieces must be an integer in 1..1024')
    zones = data.get('protected_zones')
    if not isinstance(zones, list) or not all(rect(z) for z in zones):
        raise ValueError('protected_zones must contain finite, nonempty rectangles')
    pieces = data.get('pieces')
    if not isinstance(pieces, list) or not pieces:
        raise ValueError('pieces must be nonempty')
    ids = set()
    for piece in pieces:
        if not isinstance(piece, dict):
            raise ValueError('piece must be an object')
        name = piece.get('id')
        if not isinstance(name, str) or not name or name in ids:
            raise ValueError('piece IDs must be unique nonempty strings')
        ids.add(name)
        for key in ('half_extent', 'travel'):
            value = piece.get(key)
            if not vector(value, 2) or any(v < 0 or (key == 'half_extent' and v == 0) for v in value):
                raise ValueError(f'{name}: invalid {key}')
        ex, ey = envelope(piece)
        b = data['bounds']
        if 2 * ex > b[2] - b[0] or 2 * ey > b[3] - b[1]:
            raise ValueError(f'{name}: motion envelope cannot fit bounds')
    return data


def envelope(piece):
    return [a + b for a, b in zip(piece['half_extent'], piece['travel'])]


def overlaps(a, b):
    # Touching is permitted. Consumers may add a clearance to the envelopes.
    return a[0] < b[2] and a[2] > b[0] and a[1] < b[3] and a[3] > b[1]


def placement(data, kind, x, y, occupied=()):
    if type(kind) is not int or not 0 <= kind < len(data['pieces']) or not number(x) or not number(y):
        return False
    if any(abs(v / data['grid'] - round(v / data['grid'])) > 1e-5 for v in (x, y)):
        return False
    ex, ey = envelope(data['pieces'][kind])
    r = [x-ex, y-ey, x+ex, y+ey]
    b = data['bounds']
    return (len(occupied) < data['max_pieces'] and r[0] >= b[0] and r[1] >= b[1]
            and r[2] <= b[2] and r[3] <= b[3]
            and not any(overlaps(r, zone) for zone in data['protected_zones'])
            and not any(overlaps(r, other) for other in occupied))


def header(data, source_hash):
    def values(items):
        return ', '.join(format(float(v), '.9f') + 'f' for v in items)
    zones = data['protected_zones']
    lines = ['// Generated by GameCore tools/course_contract.py. Do not edit.',
             f'// Source SHA256: {source_hash}', '#pragma once', 'namespace GameCoreCourse {',
             f'inline constexpr float Bounds[4] = {{{values(data["bounds"])}}};',
             f'inline constexpr float Grid = {values([data["grid"]])};',
             f'inline constexpr int MaxPieces = {data["max_pieces"]};',
             f'inline constexpr int ZoneCount = {len(zones)};',
             f'inline constexpr float Zones[{max(1, len(zones))}][4] = {{']
    lines += ['    {' + values(z) + '},' for z in (zones or [[0, 0, 0, 0]])]
    lines += ['};', f'inline constexpr int PieceCount = {len(data["pieces"])};',
              'inline constexpr float Envelopes[PieceCount][2] = {']
    lines += ['    {' + values(envelope(p)) + '},' for p in data['pieces']]
    return '\n'.join(lines + ['};', '}',''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', type=Path)
    parser.add_argument('--header', type=Path)
    args = parser.parse_args()
    try:
        raw = args.manifest.read_bytes()
        data = validate(json.loads(raw.decode('utf-8-sig')))
        digest = hashlib.sha256(raw).hexdigest()
        if args.header:
            output = header(data, digest)
            if not args.header.exists() or args.header.read_text(encoding='utf-8') != output:
                args.header.write_text(output, encoding='utf-8')
        print(json.dumps({'status': 'passed', 'scope': 'placement-contract-only', 'sha256': digest,
                          'pieces': len(data['pieces'])}))
    except (ValueError, OSError, KeyError, TypeError) as exc:
        parser.exit(1, f'Course contract failed: {exc}\n')


if __name__ == '__main__':
    main()
