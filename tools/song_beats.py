#!/usr/bin/env python3
"""Song beat map: estimate each song's tempo (BPM) and first-beat offset for beat-synced game life.

Part of the ambient-world-life and game-music-video workflows. Decodes each file with FFmpeg to
8 kHz mono, builds a 100 Hz onset envelope (positive energy change), scores lags against the next
eight beats over 70-180 BPM, refines the best lag to a fraction of a frame, then picks the beat
phase that lines up best with the onsets. Pure Python (no numpy).

    python tools/song_beats.py --song shanty=game/assets/audio/shampoo_island_shanty.mp3 \\
        --song tickles=game/assets/audio/spin_the_silver_thread.mp3 --out game/scripts/song_beats.gd

The output is JSON ({id: {"bpm", "offset"}}) or, for a .gd path, a GDScript `const BEATS := {...}`
(a script constant always exports from Godot, unlike a loose JSON file). A game's beat clock is then
beat = (song_seconds - offset) * bpm / 60.
"""
import argparse, json, struct, subprocess, sys
from pathlib import Path

RATE, HOP = 8000, 80          # 100 envelope frames per second
FRAMES_PER_MIN = 6000.0


def envelope_from_samples(samples):
    energy = [sum(s * s for s in samples[i:i + HOP]) / HOP for i in range(0, len(samples) - HOP, HOP)]
    onset = [max(0.0, energy[i] - energy[i - 1]) for i in range(1, len(energy))]
    peak = max(onset) if onset else 0.0
    return [o / peak for o in onset] if peak else onset


def envelope(path, start=20.0, span=90.0):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(start), '-t', str(span), '-i', str(path),
                          '-ac', '1', '-ar', str(RATE), '-f', 's16le', '-'], capture_output=True, check=True).stdout
    return envelope_from_samples(struct.unpack('<%dh' % (len(raw) // 2), raw))


def lag_score(onset, lag):
    """Similarity of the envelope with itself 1..8 beats later; long reach sharpens the estimate."""
    return sum(sum(onset[i] * onset[i + k * lag] for i in range(len(onset) - k * lag)) / k for k in range(1, 9))


def tempo(onset, low=70, high=180):
    scores = {lag: lag_score(onset, lag) for lag in range(int(FRAMES_PER_MIN / high), int(FRAMES_PER_MIN / low) + 1)}
    best = max(scores, key=scores.get)
    a, b, c = scores.get(best - 1, 0.0), scores[best], scores.get(best + 1, 0.0)
    shift = .5 * (a - c) / (a - 2 * b + c) if (a - 2 * b + c) else 0.0
    return FRAMES_PER_MIN / (best + max(-.5, min(.5, shift)))


def phase(onset, period):
    """Offset (frames) of the beat grid with a fractional period that best matches the onsets."""
    best, best_off = -1.0, 0
    for off in range(int(period)):
        score = sum(onset[int(round(off + k * period))] for k in range(int((len(onset) - off - 1) / period)))
        if score > best:
            best, best_off = score, off
    return best_off


def estimate(onset, start=20.0):
    bpm = tempo(onset)
    off = phase(onset, FRAMES_PER_MIN / bpm)
    return {'bpm': round(bpm, 2), 'offset': round((start + (off + 1) / 100.0) % (60.0 / bpm), 3)}


def render(table, out):
    if str(out).endswith('.gd'):
        return ('extends RefCounted\n## Generated by ArcoreGameCore tools/song_beats.py: tempo (BPM) and first-beat offset\n'
                '## (seconds) per song, for a beat clock. Re-run after changing a master.\n'
                'const BEATS := ' + json.dumps(table, indent=4) + '\n')
    return json.dumps(table, indent=2) + '\n'


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--song', action='append', required=True, metavar='ID=PATH', help='song id and audio file (repeat)')
    p.add_argument('--out', required=True, help='.json or .gd output')
    p.add_argument('--start', type=float, default=20.0, help='seconds to skip (intros) before analysing')
    p.add_argument('--span', type=float, default=90.0, help='seconds analysed')
    a = p.parse_args(argv)
    table = {}
    for item in a.song:
        song_id, _, path = item.partition('=')
        table[song_id] = estimate(envelope(path, a.start, a.span), a.start)
        print(song_id, table[song_id], flush=True)
    Path(a.out).write_text(render(table, a.out), encoding='utf-8')
    print(a.out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
